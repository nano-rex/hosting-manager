#!/usr/bin/env bash
# Generates every kind of site into a throwaway sandbox (no root needed, nothing
# outside the sandbox is touched) and checks the results. When nginx or Apache
# is installed, the generated configs are also checked with `nginx -t` and
# `apache2 -t` against a minimal main config inside the sandbox.
set -euo pipefail

HERE=$(cd "$(dirname "$0")" && pwd)
HM="$HERE/../hosting-manager.sh"
T=$(mktemp -d)
trap 'rm -rf "$T"' EXIT

export HM_ETC=$T/etc HM_WWW=$T/www HM_LE=$T/le HM_NGINX_LOGS=$T/logs HM_FAKE=1 HM_IPV6=${HM_IPV6:-0}
mkdir -p "$T"/etc/nginx/{sites-available,sites-enabled,conf.d} \
         "$T"/etc/apache2/{sites-available,sites-enabled,mods-enabled,conf-available,conf-enabled} "$T"/www "$T"/logs

fail=0
check() { if eval "$2"; then echo "ok   $1"; else echo "FAIL $1"; fail=1; fi; }
hm() { bash "$HM" "$@" >>"$T/out.log" 2>&1; }

# self-signed certificates standing in for Let's Encrypt
cert() {
  mkdir -p "$T/le/live/$1"
  openssl req -x509 -newkey rsa:2048 -nodes -days 1 -subj "/CN=$1" \
    -keyout "$T/le/live/$1/privkey.pem" -out "$T/le/live/$1/fullchain.pem" 2>/dev/null
}
for d in static.test php.test proxy.test old.test new.test a-old.test a-static.test a-php.test a-proxy.test a-new.test; do cert $d; done

# nginx sites
hm create static.test --server nginx --ssl
hm create php.test --server nginx --php --php-sock /run/php/php-fpm.sock --ssl --max-body 32M
hm create proxy.test --server nginx --proxy 3000 --ssl
hm create plain.test --server nginx --no-www
hm create old.test --server nginx --ssl
hm rename old.test new.test --redirect
hm create gone.test --server nginx
hm -y remove gone.test
hm create off.test --server nginx --disabled

# Apache sites
hm create a-static.test --server apache --ssl
hm create a-php.test --server apache --php --php-sock /run/php/php-fpm.sock --ssl
hm create a-proxy.test --server apache --proxy https://127.0.0.1:8443 --ssl
hm create a-plain.test --server apache --max-body 10M
hm create a-old.test --server apache --ssl
hm rename a-old.test a-new.test

# hand-made Apache sites to adopt: two vhosts in one file, a certbot pair, a
# vhost hidden in conf-enabled, and a file with other directives (left alone)
cat > "$T/etc/apache2/sites-available/legacy.conf" <<'CONF'
# generated by an old panel
<VirtualHost *:3000>
    ServerName shop.legacy.test
    ServerAlias www.shop.legacy.test
    DocumentRoot /home/legacy/public_html/shop
    php_admin_value open_basedir "/home/legacy/public_html/shop/:/tmp/"
    <Directory /home/legacy/public_html/shop>
        AllowOverride All
        Require all granted
    </Directory>
</VirtualHost>
<VirtualHost *:3001>
    ServerName blog.legacy.test
    DocumentRoot /home/legacy/public_html/blog
</VirtualHost>
CONF
cat > "$T/etc/apache2/sites-available/app.conf" <<'CONF'
<VirtualHost *:80>
    ServerName app.legacy.test
    ServerAlias www.app.legacy.test
    ProxyPass / http://127.0.0.1:5000/
RewriteEngine on
RewriteCond %{SERVER_NAME} =app.legacy.test
RewriteRule ^ https://%{SERVER_NAME}%{REQUEST_URI} [END,NE,R=permanent]
</VirtualHost>
CONF
cat > "$T/etc/apache2/sites-available/app-le-ssl.conf" <<CONF
<IfModule mod_ssl.c>
<VirtualHost *:443>
    ServerName app.legacy.test
    ProxyPass / http://127.0.0.1:5000/
SSLCertificateFile $T/le/live/app.legacy.test/fullchain.pem
SSLCertificateKeyFile $T/le/live/app.legacy.test/privkey.pem
</VirtualHost>
</IfModule>
CONF
cat > "$T/etc/apache2/conf-available/hidden.conf" <<'CONF'
<VirtualHost *:80>
    ServerName hidden.legacy.test
    ProxyPass / http://127.0.0.1:5001/
</VirtualHost>
CONF
cat > "$T/etc/apache2/conf-available/mixed.conf" <<'CONF'
ServerTokens Prod
<VirtualHost *:80>
    ServerName mixed.legacy.test
</VirtualHost>
CONF
cert app.legacy.test
# a copy of the certbot pair under another name, for the rename test
sed 's/app\.legacy\.test/pay.legacy.test/g; s/5000/5002/' "$T/etc/apache2/sites-available/app.conf" > "$T/etc/apache2/sites-available/pay.conf"
sed 's/app\.legacy\.test/pay.legacy.test/g; s/5000/5002/' "$T/etc/apache2/sites-available/app-le-ssl.conf" > "$T/etc/apache2/sites-available/pay-le-ssl.conf"
cert pay.legacy.test; cert pay.newname.test
chmod 640 "$T/etc/apache2/sites-available/legacy.conf"
for f in legacy app app-le-ssl pay pay-le-ssl; do ln -s ../sites-available/$f.conf "$T/etc/apache2/sites-enabled/$f.conf"; done
for f in hidden mixed; do ln -s ../conf-available/$f.conf "$T/etc/apache2/conf-enabled/$f.conf"; done
mkdir -p "$T/home/legacy/public_html/shop" "$T/home/legacy/public_html/blog"
echo '<?php define("ROOT", "'"$T"'/home/legacy/public_html/shop/inc");' > "$T/home/legacy/public_html/shop/config.php"
hm adopt --all
# point the adopted sites at the sandbox copy of /home, then relocate it
hm update shop.legacy.test --root "$T/home/legacy/public_html/shop"
hm update blog.legacy.test --root "$T/home/legacy/public_html/blog"
mkdir -p "$T/etc/systemd/system" "$T/home/legacy/api"
printf '[Service]\nWorkingDirectory=%s/home/legacy/api\nExecStart=/usr/bin/dotnet %s/home/legacy/api/API.dll\n' "$T" "$T" > "$T/etc/systemd/system/legacy-api.service"
hm -y relocate "$T/home/legacy" "$T/www/legacy" --fix-app-paths --rewrite-units
# --wait-dns: waits while the name doesn't resolve, then renames; units get the host name
printf '[Service]\nWorkingDirectory=/srv/hub.legacy.test\nExecStart=/usr/bin/hub -r hub.legacy.test:21117\n' > "$T/etc/systemd/system/hub.service"
hm create hub.legacy.test --server apache --proxy 7000 --ssl --no-www
cert hub.newname.test; cert keep.legacy.test
: > "$T/dns"
( sleep 3; echo "hub.newname.test 192.0.2.7" > "$T/dns" ) &
HM_FAKE_DNS=$T/dns HM_DNS_POLL=1 hm rename hub.legacy.test hub.newname.test --wait-dns --expect-ip 192.0.2.7 --rewrite-units --delete-old-cert
wait
# a failed certificate must leave the old site exactly as it was
hm create keep.legacy.test --server apache --proxy 7001 --ssl --no-www
cp "$T/etc/apache2/sites-available/keep.legacy.test.conf" "$T/keep-before.conf"
HM_FAKE_CERT_FAIL=1 hm rename keep.legacy.test keep.newname.test || true
# rename an adopted HTTPS site whose directives mention its own name
hm rename pay.legacy.test pay.newname.test --force

n=$T/etc/nginx; a=$T/etc/apache2
check "nginx static site enabled"        "[[ -L $n/sites-enabled/static.test.conf ]]"
check "www alias added for apex domain"  "grep -q 'server_name static.test www.static.test;' $n/sites-available/static.test.conf"
check "--no-www respected"               "grep -q 'server_name plain.test;' $n/sites-available/plain.test.conf"
check "https redirect on port 80"        "grep -q 'return 301 https://\$host' $n/sites-available/static.test.conf"
check "php-fpm socket used"              "grep -q 'fastcgi_pass unix:/run/php/php-fpm.sock;' $n/sites-available/php.test.conf"
check "upload limit"                     "grep -q 'client_max_body_size 32M;' $n/sites-available/php.test.conf"
check "proxy port expanded"              "grep -q 'proxy_pass http://127.0.0.1:3000;' $n/sites-available/proxy.test.conf"
check "websocket map written"            "[[ -f $n/conf.d/hosting-manager.conf ]]"
check "rename: new site served"          "grep -q 'server_name new.test www.new.test;' $n/sites-available/new.test.conf"
check "rename: old name redirects"       "grep -q 'return 301 https://new.test\$request_uri;' $n/sites-available/old.test.conf"
check "remove: config gone"              "[[ ! -e $n/sites-available/gone.test.conf && ! -e $n/sites-enabled/gone.test.conf ]]"
check "--disabled: not enabled"          "[[ -f $n/sites-available/off.test.conf && ! -e $n/sites-enabled/off.test.conf ]]"
check "apache site enabled"              "[[ -L $a/sites-enabled/a-static.test.conf ]]"
check "apache php handler"               "grep -q 'proxy:unix:/run/php/php-fpm.sock|fcgi://localhost' $a/sites-available/a-php.test.conf"
check "apache https upstream"            "grep -q 'SSLProxyEngine on' $a/sites-available/a-proxy.test.conf"
check "apache upload limit"              "grep -q 'LimitRequestBody 10485760' $a/sites-available/a-plain.test.conf"
check "apache rename without redirect"   "[[ ! -e $a/sites-available/a-old.test.conf && -f $a/sites-available/a-new.test.conf ]]"
check "list shows 19 sites"              "[[ \$(bash $HM list | grep -c '\.test ') -eq 19 ]]"
check "adopt: one file per site"         "[[ -f $a/sites-available/shop.legacy.test.conf && -f $a/sites-available/blog.legacy.test.conf ]]"
check "adopt: port and directives kept"  "grep -q '<VirtualHost \*:3000>' $a/sites-available/shop.legacy.test.conf && grep -q 'php_admin_value open_basedir' $a/sites-available/shop.legacy.test.conf"
check "adopt: aliases kept"              "grep -q 'ServerAlias www.shop.legacy.test' $a/sites-available/shop.legacy.test.conf"
check "adopt: file mode kept"            "[[ \$(stat -c %a $a/sites-available/shop.legacy.test.conf) == 640 ]]"
check "adopt: HTTP+HTTPS in one file"    "grep -q '<VirtualHost \*:443>' $a/sites-available/app.legacy.test.conf && grep -q 'RewriteCond %{SERVER_NAME} =app.legacy.test' $a/sites-available/app.legacy.test.conf"
check "adopt: certificate path kept"     "grep -q 'SSLCertificateFile $T/le/live/app.legacy.test/fullchain.pem' $a/sites-available/app.legacy.test.conf"
check "adopt: acme path not proxied"     "grep -q 'ProxyPass /.well-known/acme-challenge/ !' $a/sites-available/app.legacy.test.conf"
check "adopt: conf-enabled vhost moved"  "[[ ! -e $a/conf-enabled/hidden.conf && -L $a/sites-enabled/hidden.legacy.test.conf ]]"
check "adopt: old files out of service"  "[[ ! -e $a/sites-enabled/legacy.conf && ! -e $a/sites-available/app-le-ssl.conf ]]"
check "adopt: mixed file left alone"     "[[ -L $a/conf-enabled/mixed.conf ]] && ! bash $HM info mixed.legacy.test >/dev/null 2>&1"
check "relocate: files copied"           "[[ -f $T/www/legacy/public_html/shop/config.php ]]"
check "relocate: sites switched"         "grep -q 'DocumentRoot $T/www/legacy/public_html/shop' $a/sites-available/shop.legacy.test.conf && ! grep -q '$T/home/legacy' $a/sites-available/shop.legacy.test.conf"
check "relocate: open_basedir switched"  "grep -q 'open_basedir \"$T/www/legacy/public_html/shop/:' $a/sites-available/shop.legacy.test.conf"
check "relocate: app path fixed"         "grep -q '$T/www/legacy/public_html/shop/inc' $T/www/legacy/public_html/shop/config.php"
check "relocate: service rewritten"     "grep -q 'WorkingDirectory=$T/www/legacy/api' $T/etc/systemd/system/legacy-api.service && ! grep -q '$T/home/legacy' $T/etc/systemd/system/legacy-api.service"
check "rename adopted: names in body"    "grep -q 'RewriteCond %{SERVER_NAME} =pay.newname.test' $a/sites-available/pay.newname.test.conf && grep -q 'ServerAlias www.pay.newname.test' $a/sites-available/pay.newname.test.conf"
check "rename adopted: old site gone"    "[[ ! -e $a/sites-available/pay.legacy.test.conf ]]"
check "check is its own command"         "bash $HM check >/dev/null 2>&1 && ! bash $HM check | grep -q '^hosting-manager '"
check "wait-dns: renamed after DNS"     "[[ -f $a/sites-available/hub.newname.test.conf && ! -e $a/sites-available/hub.legacy.test.conf ]] && grep -q 'SSLCertificateFile $T/le/live/hub.newname.test' $a/sites-available/hub.newname.test.conf"
check "units: host name, not path"       "grep -q 'ExecStart=/usr/bin/hub -r hub.newname.test:21117' $T/etc/systemd/system/hub.service && grep -q 'WorkingDirectory=/srv/hub.legacy.test' $T/etc/systemd/system/hub.service"
check "failed cert: old site untouched"  "cmp -s $T/keep-before.conf $a/sites-available/keep.legacy.test.conf && [[ ! -e $a/sites-available/keep.newname.test.conf && ! -e $T/etc/hosting-manager/sites/keep.newname.test.site ]]"
check "relocate: old copy kept"          "[[ -f $T/home/legacy/public_html/shop/config.php ]]"

NGINX=$(command -v nginx || ls /usr/sbin/nginx 2>/dev/null || true)
if [[ -n $NGINX ]]; then
  cp /etc/nginx/fastcgi_params "$n/" 2>/dev/null || touch "$n/fastcgi_params"
  # copy the enabled sites with unprivileged ports, so the test runs without root
  mkdir -p "$n/test-sites"
  for f in "$n"/sites-enabled/*; do
    sed -E 's/listen (\[::\]:)?80;/listen \118080;/; s/listen (\[::\]:)?443 ssl;/listen \118443 ssl;/' "$f" > "$n/test-sites/$(basename "$f")"
  done
  cat > "$n/nginx.conf" <<CONF
pid $T/nginx.pid;
error_log $T/logs/error.log;
events {}
http {
    access_log $T/logs/access.log;
    include $n/conf.d/*.conf;
    include $n/test-sites/*;
}
CONF
  check "nginx -t accepts the configs" "'$NGINX' -t -q -p '$T' -c '$n/nginx.conf' -e '$T/logs/error.log' 2>'$T/nginx-t.log' || { cat '$T/nginx-t.log'; false; }"
else
  echo "skip nginx -t (nginx not installed)"
fi

APACHE=$(command -v apache2 || ls /usr/sbin/apache2 2>/dev/null || command -v httpd || true)
MODS=/usr/lib/apache2/modules
[[ -d $MODS ]] || MODS=/usr/lib64/httpd/modules
if [[ -n $APACHE && -d $MODS ]]; then
  {
    echo "ServerRoot $T"
    echo "Define APACHE_LOG_DIR $T/logs"
    echo "PidFile $T/apache.pid"
    echo "ErrorLog $T/logs/apache-error.log"
    echo "Listen 127.0.0.1:18080"
    echo "Listen 127.0.0.1:18443"
    echo 'LogFormat "%h %l %u %t \"%r\" %>s %O" combined'
    for m in mpm_prefork authz_core alias dir rewrite ssl headers proxy proxy_http proxy_fcgi setenvif log_config; do
      [[ -f $MODS/mod_$m.so ]] && echo "LoadModule ${m}_module $MODS/mod_$m.so"
    done
    php=$(ls "$MODS"/libphp*.so 2>/dev/null | head -1 || true)
    [[ -n $php ]] && echo "LoadModule php_module $php"
    echo "<IfModule !php_module>"
    echo "    Define NO_PHP"
    echo "</IfModule>"
    echo "Include $a/sites-enabled/*.conf"
  } > "$a/apache2.conf"
  check "apache2 -t accepts the configs" "'$APACHE' -t -f '$a/apache2.conf' >'$T/apache-t.log' 2>&1 || { cat '$T/apache-t.log'; false; }"
else
  echo "skip apache -t (Apache not installed)"
fi

if (( fail )); then echo; echo "--- hosting-manager output ---"; cat "$T/out.log"; exit 1; fi
echo "all tests passed"
